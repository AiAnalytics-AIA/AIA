#!/usr/bin/env node
/**
 * The product's icons (prototype-build PBA5, UI-2): Phosphor Regular, @phosphor-icons/core (MIT),
 * the exact version in package.json. src/design/icons.json names every Phosphor icon the product
 * draws; this writes their path data into src/components/icons/phosphor.ts, so the client ships
 * only those, as inline SVG in currentColor, and no icon file is fetched at run time.
 *
 *   node scripts/build-icons.mjs           write the module
 *   node scripts/build-icons.mjs --check   fail when it differs from what would be written
 *
 * Every Regular icon of 2.1.1 is one <path> on a 256 grid; any other shape is refused by name.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(import.meta.url);
// The package exports its SVGs by path only; its root is two levels above any of them.
const svgPath = (name) => require.resolve(`@phosphor-icons/core/regular/${name}.svg`);
const core = join(dirname(require.resolve("@phosphor-icons/core/regular/check.svg")), "../..");
const version = JSON.parse(readFileSync(join(core, "package.json"), "utf8")).version;
const names = JSON.parse(readFileSync(join(web, "src/design/icons.json"), "utf8"));
const out = join(web, "src/components/icons/phosphor.ts");

if (!Array.isArray(names) || names.some((n) => typeof n !== "string" || !/^[a-z0-9]+(-[a-z0-9]+)*$/.test(n))) {
  throw new Error("icons.json: a list of Phosphor icon names (kebab-case)");
}
const sorted = [...new Set(names)].sort();
if (sorted.length !== names.length || sorted.some((n, i) => n !== names[i])) {
  throw new Error("icons.json: keep the names sorted and once each");
}

const SHAPE = /^<svg xmlns="http:\/\/www\.w3\.org\/2000\/svg" viewBox="0 0 256 256" fill="currentColor"><path d="([^"]+)"\/><\/svg>\s*$/;
const rows = sorted.map((name) => {
  let svg;
  try {
    svg = readFileSync(svgPath(name), "utf8");
  } catch {
    throw new Error(`icons.json: Phosphor ${version} has no Regular icon "${name}"`);
  }
  const m = SHAPE.exec(svg);
  if (!m) throw new Error(`Phosphor ${name}: not one path on the 256 grid`);
  return `  "${name}": "${m[1]}",`;
});

const text = `// GENERATED by scripts/build-icons.mjs from src/design/icons.json and @phosphor-icons/core ${version}
// (MIT, Phosphor Icons). Do not edit by hand: \`npm run tokens:check\` fails CI on drift.

/** Each icon's path on Phosphor's 256 grid, Regular weight, filled in currentColor. */
export const PHOSPHOR = {
${rows.join("\n")}
} as const;

export type PhosphorName = keyof typeof PHOSPHOR;
`;

if (process.argv.includes("--check")) {
  let now = "";
  try {
    now = readFileSync(out, "utf8");
  } catch {
    /* missing */
  }
  if (now !== text) {
    console.error("icons: src/components/icons/phosphor.ts is out of date; run npm run icons");
    process.exit(1);
  }
  console.log(`icons: ${sorted.length} Phosphor ${version} icons current`);
} else {
  writeFileSync(out, text);
  console.log(`icons: wrote src/components/icons/phosphor.ts (${sorted.length} Phosphor ${version} icons)`);
}
