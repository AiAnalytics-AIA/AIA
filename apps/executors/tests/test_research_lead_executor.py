@dataclass
class RecordedBedrock:
    """Answers each request with the next scripted tool input."""

    answers: list[dict[str, Any]]
    requests: list[HttpRequest] = field(default_factory=list)

    async def send(self, request: HttpRequest, *, timeout_s: float) -> HttpResponse:
        self.requests.append(request)
        tool = request.body["toolConfig"]["tools"][0]["toolSpec"]
        answer = self.answers[min(len(self.requests), len(self.answers)) - 1]
        return HttpResponse(
            status=200,
            headers={"x-amzn-requestid": f"lead-request-{len(self.requests)}"},
            body={
                "output": {
                    "message": {
                        "role": "assistant",
                        "content": [
                            {"toolUse": {"toolUseId": "t", "name": tool["name"], "input": answer}}
                        ],
                    }
                },
                "stopReason": "tool_use",
                "usage": {"inputTokens": 900, "outputTokens": 200, "totalTokens": 1100},
            },
        )


