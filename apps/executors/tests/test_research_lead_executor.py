def worker(
    world: Any,
    database_url: str,
    store: Any,
    build: Any,
    transport: RecordedBedrock,
    *,
    configured: bool = True,
    approvals: tuple[MaterialApproval, ...] = APPROVALS,
    route_approved_for: str | None = None,
    class_gates: str = "",
) -> Worker:
    gates = {"AIA_DATA_CLASS_GATES": class_gates}
    cfg = (
        settings(**gates)
        if route_approved_for is None
        # Client-confidential material needs the route's retention stated, too.
        else settings(
            AIA_AI_ROUTE_APPROVED_FOR=route_approved_for, AIA_AI_ROUTE_RETENTION_DAYS="0", **gates
        )
    )
    executor = ResearchLeadExecutor(
        store=store,
        build=build,
        gateway=build_gateway(cfg, transport=transport, signer=Signer()) if configured else None,
        config=ResearchLeadConfig(
            policy_version=cfg.policy_version,
            max_output_tokens=cfg.study_lead_max_output_tokens,
            context_window_tokens=cfg.context_window_tokens,
            reservation_usd=cfg.study_lead_reservation_usd,
            material_approvals=approvals,
        )
        if configured
        else None,
    )
    return Worker(
        session_factory=world.sessions,
        executors=registry_for(store=store, build=build, research_lead=executor),
        settings=WorkerSettings(
            database_url=database_url,
            worker_id="lead-test",
            executors="aia_executors.registry:build_registry",
            lease_seconds=30,
            heartbeat_seconds=0.1,
            poll_seconds=0.05,
            maintenance_seconds=0.2,
        ),
    )


def hatch(world: Any) -> None:
    with world.sessions() as session:
        org = ScopeResolver(session).organization_context(
            AuthenticatedPrincipal(user_id=world.lead_id, organization_id=world.organization_id)
        )
        ResearcherLeadRepository(session, org).hatch()
        session.commit()


def post(world: Any, *, message: str | None = MESSAGE) -> str:
    """Save the design, then the researcher's message (or a greeting): the Lead turn's id."""
    with world.sessions() as session:
        scope = world.lead_scope(session)
        workspace = StudyWorkspaceRepository(session)
        if workspace.content(scope).revision is None:
            workspace.save(scope, content=CONTENT, base_revision=None)
        lead = ResearchLead(session, scope, enabled=True)
        if message is None:
            turns = lead.post(kind="greeting", stage="brief")
        else:
            turns = lead.post(kind="message", stage="brief", text=message)
        session.commit()
        return str(turns[-1]["turn_id"])


def state(world: Any) -> dict[str, Any]:
    with world.sessions() as session:
        return ResearchLead(session, world.lead_scope(session), enabled=True).state()


def lead_turn(world: Any, turn_id: str) -> dict[str, Any]:
    return next(t for t in state(world)["turns"] if t["turn_id"] == turn_id)


