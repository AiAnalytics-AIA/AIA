def test_a_turn_is_answered_once_and_its_reply_is_read_from_the_step(
    ready: Any, database_url: str, store: Any, build: Any
) -> None:
    turn_id = post(ready)
    transport = RecordedBedrock([REPLY])
    w = worker(ready, database_url, store, build, transport)
    assert w.run_once()
    assert not w.run_once()
    assert len(transport.requests) == 1
    body = transport.requests[0].body
    assert body["system"][0]["text"] == lead_prompt()
    sent = json.loads(body["messages"][0]["content"][0]["text"])
    assert next(entry["layer"] for entry in sent["context"]) == "lead"  # the prompt is the system

    turn = lead_turn(ready, turn_id)
    assert turn["status"] == "COMPLETED" and turn["reason"] is None
    output = turn["output"]
    assert output["reply"] == REPLY["reply"] and output["request"] == REPLY["request"]
    # Grounding: the edit naming a question the design does not hold is dropped and named.
    assert [e["op"] for e in output["edits"]] == ["set_text"]
    assert turn["dropped"] == [{"index": 1, "op": "question_remove", "reason": "unknown_question"}]
    # The design, the study's names and the message are Class B by rule: no operator step.
    assert turn["data_class"] == "CLASS_B_DERIVED_CLIENT"
    assert state(ready)["busy"] is False
    with ready.sessions() as session:
        scope = ready.lead_scope(session)
        run = WorkflowRepository(session, scope).get_run(turn["run_id"])
        stored = research_artifacts(session, scope, store).read_json(
            run["steps"][0]["output"]["artifact_id"]
        )
    sources = {
        (p["part"], p["data_class"], p["source"])
        for p in stored["provenance"]["material_classification"]
    }
    assert ("design", "CLASS_B_DERIVED_CLIENT", "rule:design") in sources
    assert ("study_name", "CLASS_B_DERIVED_CLIENT", "rule:study_name") in sources
    assert ("message", "CLASS_B_DERIVED_CLIENT", "rule:lead_message") in sources
    assert ("prompt", "CLASS_C_INTERNAL", "code") in sources
    assert ("lead_soul", "CLASS_C_INTERNAL", "rule:lead_files") in sources
    # What the turn could see, with each layer's class (ADR 0041 decision 3, LC1).
    manifest = stored["provenance"]["context_manifest"]
    classes = {r["layer"]: r.get("data_class") for r in manifest["layers"]}
    assert classes["design"] == "CLASS_B_DERIVED_CLIENT"
    assert classes["view"] == "CLASS_B_DERIVED_CLIENT"
    assert classes["lead"] == "CLASS_C_INTERNAL"
    assert manifest["total_bytes"] <= manifest["ceiling_bytes"]

    with ready.sessions() as session:
        events = AIUsageRepository(session, ready.lead_scope(session)).events(run_id=turn["run_id"])
    assert {e.capability for e in events} == {ModelCapability.STUDY_LEAD.value}


def test_a_sample_size_outside_the_frozen_readiness_limits_is_dropped_by_name(
    ready: Any, database_url: str, store: Any, build: Any
) -> None:
    """RQC9: the turn is frozen with the readiness limits in force, which the model is shown
    (``design.readiness``), and a set_n outside them is dropped and named, never clamped."""
    turn_id = post(ready)
    reply = {
        "reply": "Navrhuji jiný vzorek.",
        "edits": [
            {"op": "set_n", "value": 40_000, "why": "Větší vzorek."},
            {"op": "set_n", "value": 600, "why": "Rozumný vzorek."},
        ],
    }
    transport = RecordedBedrock([reply])
    assert worker(ready, database_url, store, build, transport).run_once()
    sent = json.loads(transport.requests[0].body["messages"][0]["content"][0]["text"])
    design = next(entry for entry in sent["context"] if entry["layer"] == "design")
    assert design["readiness"] == {
        "methodology_version": "aia-readiness-1",
        "sample_size": {"min": 20, "max": 10000},
    }
    turn = lead_turn(ready, turn_id)
    assert turn["status"] == "COMPLETED", turn
    assert [(e["op"], e["value"]) for e in turn["output"]["edits"]] == [("set_n", 600)]
    assert turn["dropped"] == [{"index": 0, "op": "set_n", "reason": "sample_size_out_of_range"}]


