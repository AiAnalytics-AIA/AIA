#!/usr/bin/env python3
"""Compute parity verdicts from the parity matrix and a run's test results.

The matrix (``docs/migration/parity-matrix.json``) *declares* what establishes
parity for each of the 78 reference capabilities: its gates, the tests in each
gate, and the environment each gate needs. It never stores a verdict. This tool
derives one from pytest JUnit XML, so a verdict is always a statement about a
specific run:

    PASS          every gate executed and passed, and the gates that exist are
                  enough to establish this parity type
    FAIL          a gate executed and failed -- or, with --available, a gate
                  whose environment was present did not execute at all
    NOT_EXECUTED  the gates exist but did not run here (skipped, or not
                  collected). A skip is never a pass.
    NOT_RUNNABLE  no gate exists that could establish parity: nothing ported,
                  a fixture still ungated, or only production-only tests for a
                  type that needs the reference
    NOT_REQUIRED  the capability owes no parity

Stdlib only, like the rest of ``tools/``: a checker that needs its own toolchain
gets disabled the first time that toolchain breaks.

    python tools/parity_status.py                       # declared picture, no run
    python tools/parity_status.py --junit a.xml b.xml \\
        --available postgres reference_repo \\
        --json parity-status.json --markdown parity-status.md
    python tools/parity_status.py render --write docs/migration/parity-matrix.md

Exit status: 1 when any capability is FAIL or the matrix is malformed, else 0.
NOT_EXECUTED and NOT_RUNNABLE do not fail the run -- they are reported, loudly,
and CI's step summary shows them next to the passes so nobody mistakes one for
the other.
"""

from __future__ import annotations

import argparse
import json
import sys
import xml.etree.ElementTree as ET
from collections import Counter
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
DEFAULT_MATRIX = REPO / "docs" / "migration" / "parity-matrix.json"

PASS = "PASS"
FAIL = "FAIL"
NOT_EXECUTED = "NOT_EXECUTED"
NOT_RUNNABLE = "NOT_RUNNABLE"
NOT_REQUIRED = "NOT_REQUIRED"
VERDICTS = (FAIL, NOT_RUNNABLE, NOT_EXECUTED, PASS, NOT_REQUIRED)

REFERENCE_BACKED = frozenset(
    {"reference_comparison", "reference_characterization", "reference_contract", "golden_fixture"}
)
PARITY_WEIGHT = {"EXACT": 0, "NUMERICAL": 1, "INTENTIONAL_DIFFERENCE": 2, "SEMANTIC": 3}
NO_RISK_RANK = 99

TABLE_BEGIN = "<!-- parity-matrix:begin (generated by tools/parity_status.py render) -->"
TABLE_END = "<!-- parity-matrix:end -->"


# --------------------------------------------------------------------------- #
# Test results
# --------------------------------------------------------------------------- #

PASSED = "passed"
FAILED = "failed"
SKIPPED = "skipped"
_OUTCOME_RANK = {FAILED: 0, PASSED: 1, SKIPPED: 2}


@dataclass(frozen=True)
class TestCase:
    """One test outcome from a JUnit file. ``file`` is relative to pytest's rootdir."""

    file: str
    name: str
    outcome: str


def _module_file_from_classname(classname: str) -> tuple[str, str]:
    """Recover ``(file, class_path)`` from an xunit2 classname.

    ``packages.aia_core.tests.test_x.TestThing`` -> ``packages/aia_core/tests/test_x.py``,
    ``TestThing``. The module is the last dotted component starting ``test_``.
    """
    parts = classname.split(".")
    for i in range(len(parts) - 1, -1, -1):
        if parts[i].startswith("test_"):
            return "/".join(parts[: i + 1]) + ".py", "::".join(parts[i + 1 :])
    return "/".join(parts) + ".py", ""


def parse_junit(path: Path) -> list[TestCase]:
    """Read one JUnit XML file (xunit1 or xunit2) into test outcomes."""
    cases: list[TestCase] = []
    for case in ET.parse(path).getroot().iter("testcase"):
        classname = case.get("classname", "")
        derived_file, class_path = _module_file_from_classname(classname)
        file = case.get("file") or derived_file
        name = case.get("name", "")
        if class_path:
            name = f"{class_path}::{name}"
        if case.find("failure") is not None or case.find("error") is not None:
            outcome = FAILED
        elif case.find("skipped") is not None:
            outcome = SKIPPED
        else:
            outcome = PASSED
        cases.append(TestCase(file=file.replace("\\", "/"), name=name, outcome=outcome))
    return cases


def merge_results(cases: Iterable[TestCase]) -> dict[tuple[str, str], str]:
    """Merge outcomes across runs: a failure anywhere wins, then any pass.

    The same test runs on PostgreSQL and on SQLite; passing on one and skipping
    on the other is a pass, failing on either is a failure.
    """
    merged: dict[tuple[str, str], str] = {}
    for case in cases:
        key = (case.file, case.name)
        current = merged.get(key)
        if current is None or _OUTCOME_RANK[case.outcome] < _OUTCOME_RANK[current]:
            merged[key] = case.outcome
    return merged


def _same_file(declared: str, reported: str) -> bool:
    """Match a repository-relative path against a rootdir-relative one.

    pytest reports paths relative to whichever ``pyproject.toml`` it chose as
    rootdir -- ``tests/test_x.py`` when run as ``pytest packages/aia_core``,
    ``packages/aia_core/tests/test_x.py`` when run from the root.
    """
    return declared == reported or declared.endswith("/" + reported)


def matching_outcomes(pattern: str, results: Mapping[tuple[str, str], str]) -> list[str]:
    """Outcomes of every test a gate pattern names.

    A pattern is ``path/test_file.py`` (the whole module) or
    ``path/test_file.py::test_name`` (that test and all its parametrizations).

    One test can appear under two rootdir-relative paths -- the SQLite step runs
    from the repository root, the PostgreSQL steps from the package -- so
    outcomes are merged per test *name* after path matching, not per reported
    path: passed on PostgreSQL and skipped on SQLite is one pass.
    """
    path, _, name = pattern.partition("::")
    found: dict[str, str] = {}
    for (file, case), outcome in results.items():
        if not _same_file(path, file):
            continue
        if not name or case == name or case.startswith(name + "["):
            current = found.get(case)
            if current is None or _OUTCOME_RANK[outcome] < _OUTCOME_RANK[current]:
                found[case] = outcome
    return list(found.values())


