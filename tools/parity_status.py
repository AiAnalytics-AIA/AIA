def render_report_markdown(report: Report) -> str:
    lines = ["## Parity status", ""]
    if not report.results_supplied:
        lines += [
            "> **No test results were supplied.** Every gate below is `NOT_EXECUTED` by",
            "> definition; this is the declared picture, not evidence.",
            "",
        ]
    lines += [f"Reference pinned at `{report.reference_commit}`.", ""]
    lines += ["| Verdict | All | MVP blockers |", "| --- | ---: | ---: |"]
    for verdict in VERDICTS:
        lines.append(
            f"| `{verdict}` | {report.counts.get(verdict, 0)} "
            f"| {report.blocking_counts.get(verdict, 0)} |"
        )
    lines += ["", "### Highest-risk unverified capability", ""]
    if report.highest_risk_unverified:
        top, *rest = report.highest_risk_unverified
        lines += [f"**{top}**", ""]
        lines += [f"{i}. {item}" for i, item in enumerate(rest, start=2)]
    else:
        lines.append("None: every parity-bearing capability is release-ready.")
    acc = report.acceptance
    lines += [
        "",
        f"### {acc['id']} — MVP acceptance test",
        "",
        f"`{acc['verdict']}`. {acc['not_release_ready']} of {acc['capabilities_on_path']} "
        "capabilities on the acceptance path are not release-ready "
        f"({', '.join(f'{k} {v}' for k, v in sorted(acc['not_release_ready_by_state'].items()))}).",
        "",
        "### Golden fixtures",
        "",
        "| Fixture | Capability | Source | Gate | Verdict | Runs in CI | Gap |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for row in report.fixtures:
        lines.append(
            f"| `{row['fixture']}` | `{row['capability']}` | {row['source'] or row['status']} "
            f"| {row['gate_state']} | `{row['verdict']}` "
            f"| {'yes' if row['ci_runnable'] else 'no'} | {row['gap'] or ''} |"
        )
    lines += [
        "",
        "### Capabilities",
        "",
        "| Capability | Owner | State | Parity | Verdict | Gates passed | Detail |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for s in report.capabilities:
        if s.verdict == NOT_REQUIRED:
            continue
        passed = sum(1 for g in s.gates if g.verdict == PASS)
        owner = s.owner if s.owner_confirmed else f"{s.owner} *(unconfirmed)*"
        blocker = " **B**" if s.release_blocker else ""
        lines.append(
            f"| `{s.id}`{blocker} | {owner} | {s.implementation_state} | {s.parity_type} "
            f"| `{s.verdict}` | {passed}/{len(s.gates)} | {s.detail} |"
        )
    lines += [
        "",
        f"**B** = MVP release blocker. {len(report.unowned)} capabilities have no confirmed owner.",
        "",
    ]
    return "\n".join(lines)


def render_table(matrix: Mapping[str, Any]) -> str:
    """The declared matrix as markdown, for ``parity-matrix.md``. No verdicts."""
    lines = [
        TABLE_BEGIN,
        "",
        "| Capability | Owner | State | Parity | Tolerance | Fixtures | Gates | High risk "
        "| MVP blocker |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for cid, cap in sorted(matrix["capabilities"].items()):
        owner = cap["owner"]["workstream"] + (
            "" if cap["owner"]["confirmed"] else " *(unconfirmed)*"
        )
        fixtures = ", ".join(f.split("_", 1)[0] for f in cap["fixtures"]) or "—"
        kinds = Counter(g["kind"] for g in cap["gates"])
        gates = ", ".join(f"{k} x{n}" for k, n in sorted(kinds.items())) or "—"
        tol = "—" if cap["tolerance"] is None else f"`{cap['tolerance']:g}`"
        lines.append(
            f"| `{cid}` | {owner} | {cap['implementation_state']} | {cap['parity_type']} "
            f"| {tol} | {fixtures} | {gates} | {', '.join(cap['high_risk']) or '—'} "
            f"| {'yes' if cap['release_blocker']['blocking'] else 'no'} |"
        )
    lines += ["", TABLE_END]
    return "\n".join(lines)


def splice_table(document: str, table: str) -> str:
    """Replace the generated section of ``document`` with ``table``."""
    start = document.index(TABLE_BEGIN)
    end = document.index(TABLE_END) + len(TABLE_END)
    return document[:start] + table + document[end:]


