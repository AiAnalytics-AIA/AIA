@dataclass
class GateResult:
    id: str
    kind: str
    requires: list[str]
    verdict: str
    passed: int = 0
    failed: int = 0
    skipped: int = 0
    detail: str = ""


@dataclass
class CapabilityStatus:
    id: str
    owner: str
    owner_confirmed: bool
    implementation_state: str
    parity_type: str
    verdict: str
    release_blocker: bool
    release_ready: bool
    high_risk: list[str]
    gates: list[GateResult] = field(default_factory=list)
    missing: list[str] = field(default_factory=list)
    detail: str = ""


def evaluate_gate(
    gate: Mapping[str, Any],
    results: Mapping[tuple[str, str], str] | None,
    available: frozenset[str] | None,
) -> GateResult:
    """Decide one gate from test outcomes.

    ``results is None`` means no run was supplied: nothing executed. With
    ``available`` given, a gate whose every requirement was present in this run
    but which did not execute is a FAIL -- it should have run, and a renamed or
    deselected test must not read as "environment absent".
    """
    out = GateResult(
        id=str(gate["id"]),
        kind=str(gate["kind"]),
        requires=list(gate["requires"]),
        verdict=NOT_EXECUTED,
    )
    if results is None:
        out.detail = "no test results supplied"
        return out
    uncollected: list[str] = []
    for pattern in gate["tests"]:
        outcomes = matching_outcomes(str(pattern), results)
        if not outcomes:
            uncollected.append(str(pattern))
        counts = Counter(outcomes)
        out.passed += counts[PASSED]
        out.failed += counts[FAILED]
        out.skipped += counts[SKIPPED]
    if out.failed:
        out.verdict = FAIL
        out.detail = f"{out.failed} test(s) failed"
    elif not uncollected and not out.skipped:
        out.verdict = PASS
    else:
        reasons = []
        if out.skipped:
            reasons.append(f"{out.skipped} skipped")
        if uncollected:
            reasons.append(f"{len(uncollected)} pattern(s) not collected")
        out.detail = ", ".join(reasons)
        if available is not None and set(out.requires) <= available:
            out.verdict = FAIL
            out.detail += "; its environment was available, so it should have run"
    return out


def evaluate_capability(
    cid: str,
    cap: Mapping[str, Any],
    fixtures: Mapping[str, Mapping[str, Any]],
    results: Mapping[tuple[str, str], str] | None,
    available: frozenset[str] | None,
) -> CapabilityStatus:
    status = CapabilityStatus(
        id=cid,
        owner=str(cap["owner"]["workstream"]),
        owner_confirmed=bool(cap["owner"]["confirmed"]),
        implementation_state=str(cap["implementation_state"]),
        parity_type=str(cap["parity_type"]),
        verdict=NOT_REQUIRED,
        release_blocker=bool(cap["release_blocker"]["blocking"]),
        release_ready=False,
        high_risk=list(cap["high_risk"]),
    )
    if status.parity_type == "NO_PARITY_REQUIRED":
        status.detail = "owes no parity"
        return status

    status.gates = [evaluate_gate(g, results, available) for g in cap["gates"]]
    for fid in cap["fixtures"]:
        fx = fixtures[fid]
        if fx["gates_capability"] and fx["gate"]["state"] != "GATED":
            status.missing.append(f"{fid}: {fx['gate']['state']}")
    kinds = {g.kind for g in status.gates}
    if status.parity_type == "INTENTIONAL_DIFFERENCE":
        if "production_contract" not in kinds:
            status.missing.append("no production test proving the new behaviour")
    elif not kinds & REFERENCE_BACKED:
        status.missing.append("no reference-backed gate")

    verdicts = {g.verdict for g in status.gates}
    if FAIL in verdicts:
        status.verdict = FAIL
        status.detail = "; ".join(f"{g.id}: {g.detail}" for g in status.gates if g.verdict == FAIL)
    elif status.missing:
        status.verdict = NOT_RUNNABLE
        status.detail = "; ".join(status.missing)
    elif NOT_EXECUTED in verdicts:
        status.verdict = NOT_EXECUTED
        status.detail = "; ".join(
            f"{g.id}: {g.detail}" for g in status.gates if g.verdict == NOT_EXECUTED
        )
    else:
        status.verdict = PASS
    status.release_ready = status.verdict == PASS and status.implementation_state == "IMPLEMENTED"
    return status


def _risk_rank(high_risk: Sequence[str]) -> int:
    """R1 is the highest-consequence behaviour; the reference orders them so."""
    return min((int(r[1:]) for r in high_risk), default=NO_RISK_RANK)


def rank_unverified(statuses: Iterable[CapabilityStatus]) -> list[CapabilityStatus]:
    """Order the capabilities that are not release-ready, riskiest first.

    A failed gate outranks everything. Then release blockers. Then anything
    whose gates do not pass -- a capability whose existing gates all pass but
    whose implementation is unfinished is incomplete, not unverified. Then code
    that already exists -- an unverified port can ship; an unstarted one cannot.
    Then the highest-consequence high-risk behaviour, then the strictest parity
    type.
    """
    candidates = [s for s in statuses if s.verdict != NOT_REQUIRED and not s.release_ready]

    def key(s: CapabilityStatus) -> tuple[int, int, int, int, int, int, str]:
        return (
            0 if s.verdict == FAIL else 1,
            0 if s.release_blocker else 1,
            1 if s.verdict == PASS else 0,
            0 if s.implementation_state in {"IMPLEMENTED", "PARTIAL"} else 1,
            _risk_rank(s.high_risk),
            PARITY_WEIGHT.get(s.parity_type, 9),
            s.id,
        )

    return sorted(candidates, key=key)


def why_risky(s: CapabilityStatus) -> str:
    parts = [f"{s.implementation_state}", f"{s.parity_type} parity", f"verdict {s.verdict}"]
    if s.high_risk:
        parts.append("high-risk " + "/".join(s.high_risk))
    if s.release_blocker:
        parts.append("MVP release blocker")
    text = ", ".join(parts)
    return f"{text} -- {s.detail}" if s.detail else text


@dataclass
class Report:
    reference_commit: str
    results_supplied: bool
    available: list[str] | None
    counts: dict[str, int]
    blocking_counts: dict[str, int]
    capabilities: list[CapabilityStatus]
    highest_risk_unverified: list[str]
    unowned: list[str]
    acceptance: dict[str, Any]
    fixtures: list[dict[str, Any]]

    def failed(self) -> bool:
        return self.counts.get(FAIL, 0) > 0

    def to_json(self) -> dict[str, Any]:
        return asdict(self)


def build_report(
    matrix: Mapping[str, Any],
    results: Mapping[tuple[str, str], str] | None,
    available: frozenset[str] | None,
) -> Report:
    fixtures: Mapping[str, Mapping[str, Any]] = matrix["fixtures"]
    statuses = [
        evaluate_capability(cid, cap, fixtures, results, available)
        for cid, cap in sorted(matrix["capabilities"].items())
    ]
    by_id = {s.id: s for s in statuses}
    ranked = rank_unverified(statuses)

    acceptance = matrix["mvp_acceptance"]
    on_path = sorted(s.id for s in statuses if s.release_blocker)
    not_ready = [cid for cid in on_path if not by_id[cid].release_ready]
    acceptance_verdict = NOT_RUNNABLE if acceptance["test"] is None or not_ready else NOT_EXECUTED

    gate_verdicts = {g.id: g.verdict for s in statuses for g in s.gates}
    fixture_rows = []
    for fid, fx in sorted(fixtures.items()):
        gate_verdict = gate_verdicts.get(fx["gate"].get("gate_id") or "")
        fixture_rows.append(
            {
                "fixture": fid,
                "capability": fx["capability"],
                "status": fx["status"],
                "source": fx.get("source"),
                "gate_state": fx["gate"]["state"],
                "verdict": gate_verdict or NOT_RUNNABLE,
                "ci_runnable": fx["status"] == "CAPTURED"
                and set(fx["requires"]) <= {"reference_repo"},
                "gap": fx["gap"],
            }
        )

    return Report(
        reference_commit=str(matrix["reference"]["commit"]),
        results_supplied=results is not None,
        available=sorted(available) if available is not None else None,
        counts=dict(Counter(s.verdict for s in statuses)),
        blocking_counts=dict(Counter(s.verdict for s in statuses if s.release_blocker)),
        capabilities=statuses,
        highest_risk_unverified=[f"{s.id}: {why_risky(s)}" for s in ranked[:5]],
        unowned=sorted(s.id for s in statuses if not s.owner_confirmed),
        acceptance={
            "id": acceptance["id"],
            "verdict": acceptance_verdict,
            "test": acceptance["test"],
            "capabilities_on_path": len(on_path),
            "not_release_ready": len(not_ready),
            "not_release_ready_by_state": dict(
                Counter(by_id[c].implementation_state for c in not_ready)
            ),
        },
        fixtures=fixture_rows,
    )


