def load_matrix(path: Path) -> dict[str, Any]:
    data: dict[str, Any] = json.loads(path.read_text(encoding="utf-8"))
    for key in ("reference", "fixtures", "capabilities", "mvp_acceptance"):
        if key not in data:
            raise SystemExit(f"{path}: malformed parity matrix, missing {key!r}")
    return data


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("command", nargs="?", default="report", choices=["report", "render"])
    parser.add_argument("--matrix", type=Path, default=DEFAULT_MATRIX)
    parser.add_argument("--junit", type=Path, nargs="*", default=None, help="pytest JUnit XML")
    parser.add_argument(
        "--available",
        nargs="*",
        default=None,
        help="environments present in this run (postgres, reference_repo, legacy_tree, ...); "
        "a gate needing only these that did not execute is a FAIL",
    )
    parser.add_argument("--json", type=Path, help="write the full report as JSON")
    parser.add_argument("--markdown", type=Path, help="write the report as markdown")
    parser.add_argument("--write", type=Path, help="render: splice the table into this file")
    args = parser.parse_args(argv)

    matrix = load_matrix(args.matrix)

    if args.command == "render":
        table = render_table(matrix)
        if args.write:
            args.write.write_text(splice_table(args.write.read_text("utf-8"), table), "utf-8")
            print(f"wrote the capability table into {args.write}")
        else:
            print(table)
        return 0

    results = None
    if args.junit is not None:
        cases: list[TestCase] = []
        for path in args.junit:
            if path.is_file():
                cases.extend(parse_junit(path))
            else:
                print(f"warning: {path} does not exist; its tests count as not executed")
        results = merge_results(cases)
    available = frozenset(args.available) if args.available is not None else None

    report = build_report(matrix, results, available)
    markdown = render_report_markdown(report)
    if args.json:
        args.json.write_text(json.dumps(report.to_json(), indent=2) + "\n", "utf-8")
    if args.markdown:
        args.markdown.write_text(markdown, "utf-8")

    print(f"parity status @ reference {report.reference_commit[:12]}")
    for verdict in VERDICTS:
        print(
            f"  {verdict:<13} {report.counts.get(verdict, 0):>3}"
            f"   (MVP blockers {report.blocking_counts.get(verdict, 0)})"
        )
    if report.highest_risk_unverified:
        print(f"highest-risk unverified: {report.highest_risk_unverified[0]}")
    acc = report.acceptance
    print(
        f"{acc['id']}: {acc['verdict']} -- {acc['not_release_ready']} of "
        f"{acc['capabilities_on_path']} capabilities on the path are not release-ready"
    )
    if report.failed():
        print("parity_status: FAILED -- a parity gate failed or did not run where it could.")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
